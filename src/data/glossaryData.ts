function normalizeTerm(value: string) {
  return value.replace(/\s+/g, "").replace(/[()（）]/g, "").toLowerCase();
}

export function getGlossary(id: string): GlossaryItem | undefined {
  return GLOSSARY_LIST.find((item) => item.id === id);
}

export function resolveGlossaryRef(ref: string): GlossaryItem | undefined {
  const direct = getGlossary(ref);
  if (direct) return direct;
  const q = normalizeTerm(ref);
  return GLOSSARY_LIST.find((item) => {
    if (normalizeTerm(item.titleKo) === q) return true;
    return (item.aliases ?? []).some((alias) => normalizeTerm(alias) === q);
  });
}

export function findGlossaryByTitle(titleKo: string): GlossaryItem | undefined {
  return resolveGlossaryRef(titleKo);
}
